// Command tfrefdoc improves the documentation tfplugindocs generates for a
// Terraform provider: it creates skeleton examples from the provider schema
// and rewrites the schema section of each docs page as an Argument and
// Attribute Reference with nested attributes listed under their parent.
package main

import (
	"context"
	"errors"
	"flag"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"runtime/debug"

	"github.com/adejoux/tfrefdoc/internal/example"
	"github.com/adejoux/tfrefdoc/internal/export"
	"github.com/adejoux/tfrefdoc/internal/reference"
	"github.com/adejoux/tfrefdoc/internal/tfschema"
)

// version is set at build time with -ldflags "-X main.version=...".
var version = ""

const usage = `tfrefdoc improves Terraform provider documentation generated by tfplugindocs.

Usage:
  tfrefdoc <command> [flags]

Commands:
  schema      build the provider and export its schema (terraform providers schema -json)
  examples    create the missing example files from the schema
  reference   rewrite the schema section of the docs pages
  version     print the tfrefdoc version

Typical go:generate sequence, from the provider root:
  tfrefdoc schema -o build/schema.json
  tfrefdoc examples --schema build/schema.json
  tfplugindocs generate --providers-schema build/schema.json
  tfrefdoc reference --schema build/schema.json

Run "tfrefdoc <command> -h" for the flags of a command.
`

// errFindings is returned by --check when something needs attention.
var errFindings = errors.New("check failed")

func main() {
	err := run(os.Args[1:], os.Stdout, os.Stderr)
	switch {
	case err == nil:
	case errors.Is(err, flag.ErrHelp):
	case errors.Is(err, errFindings):
		os.Exit(1)
	default:
		fmt.Fprintln(os.Stderr, "tfrefdoc:", err)
		os.Exit(1)
	}
}

func run(args []string, stdout, stderr io.Writer) error {
	if len(args) == 0 || args[0] == "-h" || args[0] == "--help" || args[0] == "help" {
		fmt.Fprint(stderr, usage)
		if len(args) == 0 {
			return errors.New("missing command")
		}
		return nil
	}
	cmd, args := args[0], args[1:]
	switch cmd {
	case "schema":
		return runSchema(args, stdout, stderr)
	case "examples":
		return runExamples(args, stdout, stderr)
	case "reference":
		return runReference(args, stdout, stderr)
	case "version", "--version":
		fmt.Fprintln(stdout, "tfrefdoc", buildVersion())
		return nil
	}
	fmt.Fprint(stderr, usage)
	return fmt.Errorf("unknown command %q", cmd)
}

func newFlagSet(name, synopsis string, stderr io.Writer) *flag.FlagSet {
	fs := flag.NewFlagSet("tfrefdoc "+name, flag.ContinueOnError)
	fs.SetOutput(stderr)
	fs.Usage = func() {
		fmt.Fprintf(stderr, "Usage: tfrefdoc %s [flags]\n\n%s\n\nFlags:\n", name, synopsis)
		fs.PrintDefaults()
	}
	return fs
}

func parse(fs *flag.FlagSet, args []string) error {
	if err := fs.Parse(args); err != nil {
		return err
	}
	if fs.NArg() > 0 {
		fs.Usage()
		return fmt.Errorf("unexpected argument %q", fs.Arg(0))
	}
	return nil
}

func runSchema(args []string, stdout, stderr io.Writer) error {
	fs := newFlagSet("schema", "Build the provider from source and export its schema with\n`terraform providers schema -json`, without registry access or terraform init.", stderr)
	var opts export.Options
	fs.StringVar(&opts.ProviderDir, "provider-dir", ".", "provider source `directory`")
	fs.StringVar(&opts.Name, "name", "", "provider short `name` (default: from go.mod, terraform-provider-<name>)")
	fs.StringVar(&opts.Namespace, "namespace", "hashicorp", "provider `namespace` in the exported address; keep hashicorp for tfplugindocs --providers-schema")
	fs.StringVar(&opts.Terraform, "terraform", "terraform", "Terraform or OpenTofu `binary`")
	output := fs.String("o", "", "write the schema to `file` instead of stdout")
	if err := parse(fs, args); err != nil {
		return err
	}
	var w io.Writer = stdout
	if *output != "" && *output != "-" {
		if err := os.MkdirAll(filepath.Dir(*output), 0o755); err != nil {
			return err
		}
		f, err := os.Create(*output)
		if err != nil {
			return err
		}
		defer f.Close()
		w = f
	}
	return export.Schema(context.Background(), w, opts)
}

func runExamples(args []string, stdout, stderr io.Writer) error {
	fs := newFlagSet("examples", "Create the example files that tfplugindocs includes in the docs pages\n(examples/resources/<name>/resource.tf, ...) when they are missing.\nExisting files are never modified. Generated files start with a TODO line\nuntil they are reviewed.", stderr)
	schemaPath := fs.String("schema", "", "provider schema JSON `file` (required)")
	dir := fs.String("examples-dir", "examples", "examples `directory`")
	provider := fs.String("provider", "", "provider `address` when the schema contains several")
	requiredOnly := fs.Bool("required-only", false, "do not add the optional arguments as comments")
	withImport := fs.Bool("import", false, "also create examples/resources/<name>/import.sh")
	check := fs.Bool("check", false, "write nothing; fail if examples are missing or still contain the TODO line")
	if err := parse(fs, args); err != nil {
		return err
	}
	p, err := loadSchema(fs, *schemaPath, *provider)
	if err != nil {
		return err
	}

	g := example.New(p, example.Options{RequiredOnly: *requiredOnly})
	missing, err := g.Missing(*dir, *withImport)
	if err != nil {
		return err
	}
	if *check {
		unreviewed, err := example.Unreviewed(*dir)
		if err != nil {
			return err
		}
		for _, f := range missing {
			fmt.Fprintf(stderr, "missing example: %s\n", filepath.Join(*dir, f.Path))
		}
		for _, f := range unreviewed {
			fmt.Fprintf(stderr, "example not reviewed (remove the TODO line once done): %s\n", filepath.Join(*dir, f))
		}
		if len(missing)+len(unreviewed) > 0 {
			return errFindings
		}
		fmt.Fprintln(stdout, "All examples are present and reviewed.")
		return nil
	}
	if err := example.Write(*dir, missing); err != nil {
		return err
	}
	for _, f := range missing {
		fmt.Fprintf(stdout, "created %s\n", filepath.Join(*dir, f.Path))
	}
	return nil
}

func runReference(args []string, stdout, stderr io.Writer) error {
	fs := newFlagSet("reference", "Replace the schema section generated by tfplugindocs in each docs page by an\nArgument Reference and an Attribute Reference, with nested attributes and\nblocks listed under their parent. Run it after tfplugindocs generate.", stderr)
	schemaPath := fs.String("schema", "", "provider schema JSON `file` (required)")
	dir := fs.String("docs-dir", "docs", "rendered docs `directory`")
	provider := fs.String("provider", "", "provider `address` when the schema contains several")
	maxDepth := fs.Int("max-depth", 3, "nesting `levels` rendered under their parent; deeper levels get their own sub-section")
	check := fs.Bool("check", false, "write nothing; fail if a page is not up to date")
	verbose := fs.Bool("v", false, "also list unchanged and skipped pages")
	if err := parse(fs, args); err != nil {
		return err
	}
	p, err := loadSchema(fs, *schemaPath, *provider)
	if err != nil {
		return err
	}

	results, err := reference.UpdateDocs(*dir, p, reference.Options{MaxDepth: *maxDepth}, *check)
	if err != nil {
		return err
	}
	changed := 0
	for _, r := range results {
		path := filepath.Join(*dir, r.Path)
		switch {
		case r.Skipped != "":
			if *verbose {
				fmt.Fprintf(stderr, "skipped %s: %s\n", path, r.Skipped)
			}
		case r.Changed:
			changed++
			if *check {
				fmt.Fprintf(stderr, "not up to date: %s\n", path)
			} else {
				fmt.Fprintf(stdout, "updated %s\n", path)
			}
		case *verbose:
			fmt.Fprintf(stdout, "unchanged %s\n", path)
		}
	}
	if *check && changed > 0 {
		return errFindings
	}
	return nil
}

func loadSchema(fs *flag.FlagSet, path, provider string) (*tfschema.Provider, error) {
	if path == "" {
		fs.Usage()
		return nil, errors.New("--schema is required")
	}
	return tfschema.Load(path, provider)
}

func buildVersion() string {
	if version != "" {
		return version
	}
	if info, ok := debug.ReadBuildInfo(); ok && info.Main.Version != "" {
		return info.Main.Version
	}
	return "dev"
}
