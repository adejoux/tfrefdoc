// Package reference renders the "Argument Reference" and "Attribute
// Reference" of a provider object as Markdown, with nested attributes and
// blocks listed under their parent, and replaces the schema section that
// tfplugindocs generates in docs/ pages.
package reference

import (
	"fmt"
	"sort"
	"strings"

	tfjson "github.com/hashicorp/terraform-json"
	"github.com/zclconf/go-cty/cty"

	"github.com/adejoux/tfrefdoc/internal/tfschema"
)

// Markers delimiting the generated section in a page.
const (
	tfplugindocsMarker = "<!-- schema generated by tfplugindocs -->"
	startMarker        = "<!-- schema generated by tfrefdoc -->"
	endMarker          = "<!-- end of schema generated by tfrefdoc -->"
)

// Options tunes the rendering.
type Options struct {
	// MaxDepth is the number of nesting levels rendered inline under their
	// parent. Deeper levels get their own "Nested schema" sub-section.
	// Values below 1 mean the default (3).
	MaxDepth int
}

// Render returns the reference section of an entity, delimited by markers.
func Render(e tfschema.Entity, opts Options) string {
	if opts.MaxDepth < 1 {
		opts.MaxDepth = 3
	}
	r := &renderer{opts: opts}
	r.entity(e)
	return r.out.String()
}

type renderer struct {
	opts Options
	out  strings.Builder
	// deferred nested schemas, rendered after the main lists.
	deferred []deferredNode
}

type deferredNode struct {
	path string
	node node
}

// node is anything that can have children in the reference tree.
type node struct {
	// arguments mode: children are split into required / optional /
	// read-only; otherwise all children are read-only.
	readOnly bool
	attrs    map[string]*tfjson.SchemaAttribute
	blocks   map[string]*tfjson.SchemaBlockType
	object   map[string]cty.Type // object type fields (read-only values)
}

func (n node) empty() bool {
	return len(n.attrs) == 0 && len(n.blocks) == 0 && len(n.object) == 0
}

func (r *renderer) printf(format string, args ...any) { fmt.Fprintf(&r.out, format, args...) }

func (r *renderer) entity(e tfschema.Entity) {
	b := e.Block
	r.printf("%s\n", startMarker)

	args := node{attrs: map[string]*tfjson.SchemaAttribute{}, blocks: b.NestedBlocks}
	attrs := node{readOnly: true, attrs: map[string]*tfjson.SchemaAttribute{}}
	for name, a := range b.Attributes {
		if tfschema.IsArgument(a) {
			args.attrs[name] = a
		} else {
			attrs.attrs[name] = a
		}
	}

	hasArgs := !args.empty()
	if hasArgs {
		r.printf("## Argument Reference\n\n")
		if e.Kind == tfschema.KindProvider {
			r.printf("The following arguments are supported in the `provider` block:\n\n")
		} else {
			r.printf("The following arguments are supported:\n\n")
		}
		r.children("", args, 0)
		r.printf("\n")
	}
	if !attrs.empty() {
		r.printf("## Attribute Reference\n\n")
		if hasArgs {
			r.printf("In addition to the arguments above, the following attributes are exported:\n\n")
		} else {
			r.printf("The following attributes are exported:\n\n")
		}
		r.children("", attrs, 0)
		r.printf("\n")
	}
	if !hasArgs && attrs.empty() {
		r.printf("## Argument Reference\n\nThis %s has no arguments.\n\n", strings.ReplaceAll(string(e.Kind), "_", " "))
	}

	for i := 0; i < len(r.deferred); i++ { // deferred may grow while rendering
		d := r.deferred[i]
		r.printf("<a id=\"%s\"></a>\n### Nested schema for `%s`\n\n", anchor(d.path), d.path)
		r.children(d.path, d.node, 0)
		r.printf("\n")
	}
	r.printf("%s\n", endMarker)
}

// item is one line of the reference tree.
type item struct {
	name  string
	label string
	desc  string
	child node
	group int // sort group: 0 required, 1 optional, 2 read-only
}

// children renders the children of a node as a (possibly nested) list.
func (r *renderer) children(path string, n node, depth int) {
	var items []item
	for name, a := range n.attrs {
		it := item{name: name, desc: a.Description}
		switch {
		case n.readOnly || tfschema.IsReadOnly(a):
			it.group = 2
		case a.Required:
			it.group = 0
		default:
			it.group = 1
		}
		mode := ""
		if !n.readOnly {
			mode = []string{"Required", "Optional", "Read-only"}[it.group]
		}
		it.label = labels(attrType(a), mode, flag(a.Sensitive, "Sensitive"), flag(a.WriteOnly, "Write-only"), flag(a.Deprecated, "Deprecated"))
		if nt := a.AttributeNestedType; nt != nil {
			it.label = labels(nestedTypeLabel(nt), mode, limits(nt.MinItems, nt.MaxItems), flag(a.Sensitive, "Sensitive"), flag(a.WriteOnly, "Write-only"), flag(a.Deprecated, "Deprecated"))
			it.child = node{readOnly: n.readOnly || it.group == 2, attrs: nt.Attributes}
		} else if obj, ok := objectOf(a.AttributeType); ok {
			it.child = node{readOnly: true, object: obj}
		}
		items = append(items, it)
	}
	for name, bt := range n.blocks {
		it := item{name: name, group: 1}
		if bt.MinItems > 0 {
			it.group = 0
		}
		var b *tfjson.SchemaBlock
		if bt.Block != nil {
			b = bt.Block
			it.desc = b.Description
		} else {
			b = &tfjson.SchemaBlock{}
		}
		mode := "Optional"
		if it.group == 0 {
			mode = "Required"
		}
		it.label = labels(blockLabel(bt.NestingMode), mode, limits(bt.MinItems, bt.MaxItems), flag(b.Deprecated, "Deprecated"))
		it.child = node{attrs: b.Attributes, blocks: b.NestedBlocks}
		items = append(items, it)
	}
	for name, t := range n.object {
		it := item{name: name, group: 2, label: typeLabel(t)}
		if obj, ok := objectOf(t); ok {
			it.child = node{readOnly: true, object: obj}
		}
		items = append(items, it)
	}
	sort.SliceStable(items, func(i, j int) bool {
		if items[i].group != items[j].group {
			return items[i].group < items[j].group
		}
		return items[i].name < items[j].name
	})

	indent := strings.Repeat("  ", depth)
	for _, it := range items {
		full := join(path, it.name)
		line := fmt.Sprintf("%s- `%s` (%s)", indent, it.name, it.label)
		hasChild := !it.child.empty()
		deferChild := hasChild && depth+1 >= r.opts.MaxDepth
		desc := strings.TrimSpace(it.desc)
		if deferChild {
			if desc != "" && !strings.HasSuffix(desc, ".") {
				desc += "."
			}
			desc = strings.TrimSpace(desc + fmt.Sprintf(" See [nested schema](#%s).", anchor(full)))
		}
		if desc != "" {
			line += " " + indentContinuation(desc, indent+"  ")
		}
		r.printf("%s\n", line)
		switch {
		case deferChild:
			r.deferred = append(r.deferred, deferredNode{path: full, node: it.child})
		case hasChild:
			r.children(full, it.child, depth+1)
		}
	}
}

// --- labels ------------------------------------------------------------

func labels(parts ...string) string {
	var out []string
	for _, p := range parts {
		if p != "" {
			out = append(out, p)
		}
	}
	return strings.Join(out, ", ")
}

func flag(b bool, s string) string {
	if b {
		return s
	}
	return ""
}

func limits(min, max uint64) string {
	switch {
	case min > 0 && max > 0 && min == max:
		return fmt.Sprintf("Exactly %d", min)
	case min > 0 && max > 0:
		return fmt.Sprintf("Min: %d, Max: %d", min, max)
	case min > 0:
		return fmt.Sprintf("Min: %d", min)
	case max > 0:
		return fmt.Sprintf("Max: %d", max)
	}
	return ""
}

func blockLabel(m tfjson.SchemaNestingMode) string {
	switch m {
	case tfjson.SchemaNestingModeList:
		return "Block List"
	case tfjson.SchemaNestingModeSet:
		return "Block Set"
	case tfjson.SchemaNestingModeMap:
		return "Block Map"
	}
	return "Block"
}

func nestedTypeLabel(nt *tfjson.SchemaNestedAttributeType) string {
	switch nt.NestingMode {
	case tfjson.SchemaNestingModeList:
		return "List of Object"
	case tfjson.SchemaNestingModeSet:
		return "Set of Object"
	case tfjson.SchemaNestingModeMap:
		return "Map of Object"
	}
	return "Object"
}

func attrType(a *tfjson.SchemaAttribute) string {
	if a.AttributeType == cty.NilType {
		return "Dynamic"
	}
	return typeLabel(a.AttributeType)
}

// typeLabel names a cty type in plain words: "List of String".
func typeLabel(t cty.Type) string {
	switch {
	case t == cty.String:
		return "String"
	case t == cty.Number:
		return "Number"
	case t == cty.Bool:
		return "Boolean"
	case t == cty.DynamicPseudoType:
		return "Dynamic"
	case t.IsListType():
		return "List of " + typeLabel(t.ElementType())
	case t.IsSetType():
		return "Set of " + typeLabel(t.ElementType())
	case t.IsMapType():
		return "Map of " + typeLabel(t.ElementType())
	case t.IsObjectType():
		return "Object"
	case t.IsTupleType():
		return "Tuple"
	}
	return t.FriendlyName()
}

// objectOf returns the fields of an object type, or of the element type of a
// collection of objects.
func objectOf(t cty.Type) (map[string]cty.Type, bool) {
	for t.IsListType() || t.IsSetType() || t.IsMapType() {
		t = t.ElementType()
	}
	if t.IsObjectType() && len(t.AttributeTypes()) > 0 {
		return t.AttributeTypes(), true
	}
	return nil, false
}

// --- helpers -----------------------------------------------------------

func join(prefix, name string) string {
	if prefix == "" {
		return name
	}
	return prefix + "." + name
}

// anchor is the HTML anchor of a nested schema sub-section.
func anchor(path string) string {
	return "nested--" + strings.ReplaceAll(path, ".", "--")
}

// indentContinuation indents the lines after the first one so a multi-line
// description stays inside its list item.
func indentContinuation(s, indent string) string {
	lines := strings.Split(s, "\n")
	for i := 1; i < len(lines); i++ {
		if strings.TrimSpace(lines[i]) == "" {
			lines[i] = ""
			continue
		}
		lines[i] = indent + strings.TrimSpace(lines[i])
	}
	return strings.Join(lines, "\n")
}
