package reference

import (
	"errors"
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/adejoux/tfrefdoc/internal/testutil"
	"github.com/adejoux/tfrefdoc/internal/tfschema"
)

func testdata(parts ...string) string {
	return filepath.Join(append([]string{"..", "..", "testdata"}, parts...)...)
}

func TestRender(t *testing.T) {
	for _, fx := range []string{"tls", "acme"} {
		p, err := tfschema.Load(testdata(fx+".json"), "")
		if err != nil {
			t.Fatal(err)
		}
		for _, e := range p.Entities() {
			path := PagePath(p, e)
			t.Run(fx+"/"+path, func(t *testing.T) {
				testutil.Golden(t, testdata("golden", fx, "reference", path), Render(e, Options{}))
			})
		}
	}
}

func TestReplaceSection(t *testing.T) {
	p, err := tfschema.Load(testdata("tls.json"), "")
	if err != nil {
		t.Fatal(err)
	}
	var section string
	for _, e := range p.Entities() {
		if e.Name == "tls_cert_request" {
			section = Render(e, Options{})
		}
	}
	page, err := os.ReadFile(testdata("tfplugindocs-cert_request.md"))
	if err != nil {
		t.Fatal(err)
	}
	once, err := ReplaceSection(string(page), section)
	if err != nil {
		t.Fatal(err)
	}
	testutil.Golden(t, testdata("golden", "tls", "page-cert_request.md"), once)

	twice, err := ReplaceSection(once, section)
	if err != nil || twice != once {
		t.Errorf("ReplaceSection must be idempotent (err=%v)", err)
	}
	if !strings.Contains(once, "## Example Usage") || strings.Contains(once, "### Nested Schema for") {
		t.Error("the page around the schema section must be kept and the tfplugindocs schema removed")
	}

	if _, err := ReplaceSection("# Title\n\nHand-written page.\n", section); !errors.Is(err, ErrNoSchemaSection) {
		t.Errorf("expected ErrNoSchemaSection, got %v", err)
	}
}

func TestReplaceSectionKeepsFollowingSections(t *testing.T) {
	page := "# r\n\n<!-- schema generated by tfplugindocs -->\n## Schema\n\n### Required\n\n- `a` (String)\n\n## Import\n\nimport text\n"
	out, err := ReplaceSection(page, "<!-- schema generated by tfrefdoc -->\nNEW\n<!-- end of schema generated by tfrefdoc -->\n")
	if err != nil {
		t.Fatal(err)
	}
	want := "# r\n\n<!-- schema generated by tfrefdoc -->\nNEW\n<!-- end of schema generated by tfrefdoc -->\n\n## Import\n\nimport text\n"
	if out != want {
		t.Errorf("got:\n%q\nwant:\n%q", out, want)
	}
}

func TestMaxDepth(t *testing.T) {
	p, err := tfschema.Load(testdata("acme.json"), "")
	if err != nil {
		t.Fatal(err)
	}
	for _, e := range p.Entities() {
		if e.Name != "acme_server" {
			continue
		}
		if out := Render(e, Options{MaxDepth: 1}); !strings.Contains(out, "### Nested schema for `rule.source`") {
			t.Errorf("with MaxDepth 1, rule.source must get its own section:\n%s", out)
		}
		if out := Render(e, Options{MaxDepth: 10}); strings.Contains(out, "### Nested schema") {
			t.Errorf("with MaxDepth 10, everything must be inline:\n%s", out)
		}
	}
}
